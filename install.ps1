# Generates the two cordis.patch.yml files for this checkout.
#
#   .\install.ps1 -Project "C:\work\my-project"
#
# -Project  is the folder your DSH session works in. It becomes BRIDGE_CWD (messages
#            sent by bridge_send carry this project) and the cwd the wake plugin
#            uses to pick which session to wake. Defaults to the folder that
#            contains this repository.
# -NodePath the node.exe DSH should launch mcp.mjs with. Defaults to the node on PATH.
# -Port     bus port. Defaults to 8787.
param(
  [string] $Project = '',
  [string] $NodePath = '',
  [int] $Port = 8787
)

$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot

if (-not $Project) { $Project = Split-Path -Parent $here }
if (-not (Test-Path -LiteralPath $Project)) { throw "project folder not found: $Project" }
$Project = (Resolve-Path -LiteralPath $Project).Path

if (-not $NodePath) {
  $cmd = Get-Command node -ErrorAction SilentlyContinue
  if (-not $cmd) { throw 'node.exe not found on PATH; pass -NodePath' }
  $NodePath = $cmd.Source
}
if (-not (Test-Path -LiteralPath $NodePath)) { throw "node not found: $NodePath" }

$mcp = Join-Path $here 'mcp.mjs'
if (-not (Test-Path -LiteralPath $mcp)) { throw "mcp.mjs not found at $mcp" }

# YAML single-quoted scalars: only the single quote itself needs doubling.
function Q([string] $s) { "'" + $s.Replace("'", "''") + "'" }

$dshPatch = @"
# Generated by install.ps1 -- do not edit by hand.
- insert:
    - id: codex-bridge-mcp
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: codex_bridge
        transport: stdio
        command: $(Q $NodePath)
        args:
          - $(Q $mcp)
        env:
          BRIDGE_PEER: dsh
          # Messages sent by bridge_send carry this project instead of showing up
          # in every project inbox. One profile has one folder; change it when the
          # profile moves.
          BRIDGE_CWD: $(Q $Project)
        failOnStartupError: false
    - id: codex-bridge-panel
      name: '@local/codex-bridge'
"@

$wakePatch = @"
# Generated by install.ps1 -- do not edit by hand.
- insert:
    - id: codex-bridge-wake
      name: '@local/codex-bridge-wake'
      config:
        port: $Port
        peer: dsh
        # Only wake sessions whose working directory is this one.
        cwd: $(Q $Project)
"@

$utf8 = New-Object System.Text.UTF8Encoding($false)
$dshOut = Join-Path $here 'dsh-bundle\cordis.patch.yml'
$wakeOut = Join-Path $here 'wake-bundle\cordis.patch.yml'
[System.IO.File]::WriteAllText($dshOut, $dshPatch, $utf8)
[System.IO.File]::WriteAllText($wakeOut, $wakePatch, $utf8)

Write-Host "wrote $dshOut"
Write-Host "wrote $wakeOut"
Write-Host "node    -> $NodePath"
Write-Host "mcp.mjs -> $mcp"
Write-Host "project -> $Project (port $Port)"
Write-Host ""
Write-Host ('Next: codex mcp add codex-bridge -- node "' + $mcp + '"')
Write-Host "Then install dsh-bundle and wake-bundle from the DSH Plugins page and restart DSH."
